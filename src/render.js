// Turning canonical templates into one client's files. Everything here is
// pure (no network, no disk) so it can be unit tested and dry-run.

const TOKEN = /\{\{([A-Z0-9_]+)\}\}/g;

// The tokens a template may use. Built from the client config plus values
// that only exist mid-build (worker URL, tool secret, KB file id).
export function tokensFor(client, extra = {}) {
  return {
    CLIENT_NAME: client.name,
    CLIENT_SLUG: client.slug,
    CLIENT_WEBSITE: client.website ?? '',
    CLIENT_TZ: client.timezone,
    SPOKEN_TZ: client.spokenTimezone,
    CLIENT_HOURS: client.hoursText ?? '',
    AREA_CODE: client.areaCode,
    RECEPTIONIST: client.receptionist,
    TOOL_PREFIX: client.derived.toolPrefix,
    WORKER_NAME: client.derived.workerName,
    EVENT_PREFIX: client.derived.eventPrefix,
    CONSULT_SERVICE: client.consultService ? client.services[client.consultService].label : '',
    CONSULT_SERVICE_KEY: client.consultService ?? '',
    FRONT_DESK_SERVICES: client.frontDesk.join(', '),
    ...extra,
  };
}

// Replace {{TOKEN}}s in a string. Unknown tokens are an error, never left
// in place: a literal "{{CLIENT_NAME}}" reaching a caller is a failed build.
export function renderString(text, tokens) {
  const missing = new Set();
  const out = text.replace(TOKEN, (whole, name) => {
    if (!(name in tokens)) {
      missing.add(name);
      return whole;
    }
    return String(tokens[name]);
  });
  if (missing.size) throw new Error(`template uses unknown token(s): ${[...missing].join(', ')}`);
  return out;
}

// Render every string inside a JSON value.
export function renderDeep(value, tokens) {
  if (typeof value === 'string') return renderString(value, tokens);
  if (Array.isArray(value)) return value.map((v) => renderDeep(v, tokens));
  if (value && typeof value === 'object') {
    return Object.fromEntries(Object.entries(value).map(([k, v]) => [k, renderDeep(v, tokens)]));
  }
  return value;
}

export function tokensUsed(text) {
  return [...new Set([...text.matchAll(TOKEN)].map((m) => m[1]))];
}

// Leakage check: none of the forbidden strings (other clients' names, the
// canonical build's name) may appear anywhere in the output.
export function findLeaks(text, forbidden) {
  const lower = text.toLowerCase();
  return forbidden.filter((f) => f && lower.includes(String(f).toLowerCase()));
}

// Typographic punctuation in spoken text (prompt, first message). Reported
// rather than rejected: fix it in the canonical prompt, then re-pull.
const PUNCT_NAMES = {
  '–': 'en dash',
  '—': 'em dash',
  '‘': 'curly quote',
  '’': 'curly quote',
  '“': 'curly quote',
  '”': 'curly quote',
  '…': 'ellipsis',
  ' ': 'non-breaking space',
};
const PUNCT = new RegExp(`[${Object.keys(PUNCT_NAMES).join('')}]`, 'g');

export function nonAsciiPunctuation(text) {
  return [...String(text).matchAll(PUNCT)].map((m) => {
    const context = text.slice(Math.max(0, m.index - 25), m.index + 26).replace(/\s+/g, ' ');
    return `${PUNCT_NAMES[m[0]]} in "...${context}..."`;
  });
}

const MARK_START = '// @factory:client-config:start';
const MARK_END = '// @factory:client-config:end';

// The per-client block of the Worker. Field names inside each service follow
// canonical.yaml (worker.serviceFields) so they match what the canonical
// Worker already reads.
export function workerConfigBlock(client, fields = {}) {
  const f = { label: 'name', minutes: 'duration', aliases: 'aliases', ...fields };
  const services = {};
  for (const [key, svc] of Object.entries(client.services)) {
    services[key] = {
      [f.label]: svc.label,
      [f.minutes]: svc.minutes,
      [f.aliases]: (svc.aliases ?? []).map((a) => String(a).toLowerCase()),
    };
  }
  const { open, close, byDay } = client.hoursMinutes;
  return [
    MARK_START,
    '// Generated by agent-factory from the client config. Do not edit by hand;',
    '// change the client.yaml and rebuild.',
    `const BUSINESS_NAME = ${JSON.stringify(client.name)};`,
    `const TZ = ${JSON.stringify(client.timezone)};`,
    `const OPEN = ${open};`,
    `const CLOSE = ${close};`,
    '// Day of week (0 = Sunday) to [open, close] in minutes after midnight, or null when closed.',
    `const HOURS_BY_DAY = ${JSON.stringify(byDay)};`,
    `const CLOSE_BY_DAY = Object.fromEntries(Object.entries(HOURS_BY_DAY).map(([d, h]) => [d, h ? h[1] : null]));`,
    `const EVENT_PREFIX = ${JSON.stringify(client.derived.eventPrefix)};`,
    `const SERVICES = ${JSON.stringify(services, null, 2)};`,
    `const FRONT_DESK = ${JSON.stringify(client.frontDesk)};`,
    MARK_END,
  ].join('\n');
}

// Swap the marked block in the canonical Worker for this client's block.
export function renderWorker(template, client, fields) {
  const start = template.indexOf(MARK_START);
  const end = template.indexOf(MARK_END);
  if (start === -1 || end === -1 || end < start) {
    throw new Error(
      `canonical Worker has no ${MARK_START} ... ${MARK_END} block. ` +
        'Wrap its client constants (SERVICES, TZ, OPEN, CLOSE, ...) in those markers once; see README.',
    );
  }
  if (template.indexOf(MARK_START, start + 1) !== -1) throw new Error('canonical Worker has more than one client-config block');
  return template.slice(0, start) + workerConfigBlock(client, fields) + template.slice(end + MARK_END.length);
}

// Fields Vapi sets itself. They must be removed before a canonical object is
// posted as a new one.
const READ_ONLY = ['id', 'orgId', 'createdAt', 'updatedAt', 'isServerUrlSecretSet'];

export function stripReadOnly(obj) {
  const copy = structuredClone(obj);
  for (const k of READ_ONLY) delete copy[k];
  return copy;
}
